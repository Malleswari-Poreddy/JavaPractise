package Day1;

public class ValuePositiveNegativeCheck {

	public static void main(String[] args) {
		int a = 0;
		if(a>=0) {
			System.out.println("a ("+a+") is a positive value");
		}else if(a<=0) {
			System.out.println("a ("+a+") is a negative value");
		}else
		{
			System.out.println("a is equal to 0");
			
		}
	}

}
