package Day1;

public class VariablesExample {

	public static void main(String[] args) {
		String name = "Poreddy Malleswari";
		int age = 31;
		double  salary = 55000.09;
		char rating = 'A';
		boolean isAutomationTester = true;
		String mobileBrand ="Iphone";
		int mobileModel = 14;
		int price = 50000;
		boolean is5GSupported = true;
		System.out.println("Name: "+ name);
		System.out.println("Age: "+ age);
		System.out.println("Salary: "+ salary);
		System.out.println("Rating: "+ rating);
		System.out.println("Automation tester: "+isAutomationTester);
		System.out.println("Mobile Brand: "+ mobileBrand);
		System.out.println("Mobile Model: "+mobileModel);
		System.out.println("Mobile Price: "+ price);
		System.out.println("Mobile supports 5G Network: "+is5GSupported);
	}

}
/*What are Variables and Data Types?
Variable = A name for a memory location where data is stored.

Data Type = Tells Java what kind of data you are storing.

🧠 Common Data Types:
Data Type	Example	Meaning
int	10, -20	Whole numbers
double	12.5, -34.7	Decimal numbers
char	'a', 'Z'	Single character
boolean	true, false	Logical values
String	"Hello", "Java"	Group of characters (not primitive)*/